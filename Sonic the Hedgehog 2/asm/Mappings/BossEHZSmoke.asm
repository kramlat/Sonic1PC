.int:		dc.w .f0-.int
		dc.w .f1-.int
		dc.w .f2-.int
		dc.w .f3-.int
.f0:		dc.w 1			
		dc.w $F805,    0,    0,$FFF8
.f1:		dc.w 1			
		dc.w $F805,    4,    2,$FFF8
.f2:		dc.w 1			
		dc.w $F805,    8,    4,$FFF8
.f3:		dc.w 1			
		dc.w $F805,   $C,    6,$FFF8
