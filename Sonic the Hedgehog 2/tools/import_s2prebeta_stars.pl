#!/usr/bin/perl
# The invincibility stars of the Sonic 2 pre-beta (object $35: S2PREBETA gives the disassembly's folder, default ~/Projects/s2prebeta-disasm) from its Data/Objects/Obj_0x35.asm, the mappings in S2140992.asm and Data/Art/InvStars.nem:
#   res/Art/Invincibility              the stars' art (Nemesis)
#   res/Mappings/InvincibilityStars    the stars' 9 frames (Sonic 2's format: the build converts them)
#   src/Object/InvincibilityStarsData.h  the tables of where each star is (the object's own: the offsets from Sonic by his angle, the two orbits by frame parity, and the trailing pair)
# Run it in the Sonic 2 folder: import_s2prebeta_stars.pl
use strict;
use warnings;

my $base = $ENV{S2PREBETA} // "$ENV{HOME}/Projects/s2prebeta-disasm";
my $src = "$base/Data/Objects/Obj_0x35.asm";
open my $f, '<', $src or die "$src: $!\n";
my @lines = <$f>;
close $f;
s/;.*// for @lines;

# the data after each label: its dc.b / dc.w values as bytes
my (%data, $label);
for (@lines) {
    if (/^(Offset_0x01862A|Offset_0x01864A|Offset_0x0187B2|Offset_0x01891A):\s*$/) { $label = $1; $data{$label} = []; next }
    next unless defined $label;
    if (/^\s*dc\.b\s+(.*\S)/) { push @{ $data{$label} }, map { hex s/^\s*\$//r } split /,/, $1 }
    elsif (/^\s*dc\.w\s+(.*\S)/) { push @{ $data{$label} }, map { my $w = hex s/^\s*\$//r; ($w >> 8, $w & 0xFF) } split /,/, $1 }
}
my %names = (Offset_0x01862A => 'stars_angle', Offset_0x01864A => 'stars_orbit_even', Offset_0x0187B2 => 'stars_orbit_odd', Offset_0x01891A => 'stars_trail');
my $out = "// Generated by tools/import_s2prebeta_stars.pl from the pre-beta's Data/Objects/Obj_0x35.asm: where its stars are (see InvincibilityStars.c)\n#ifndef _INVINCIBILITYSTARSDATA_H\n#define _INVINCIBILITYSTARSDATA_H\n\n#include <stdint.h>\n\n";
for my $l (sort keys %names) {
    my @b = @{ $data{$l} or die "no $l\n" };
    $out .= "static const int8_t $names{$l}\[" . scalar(@b) . "] = {";
    for my $i (0 .. $#b) { $out .= "\n   " if $i % 12 == 0; $out .= sprintf(' %d,', $b[$i] > 127 ? $b[$i] - 256 : $b[$i]) }
    $out .= "\n};\n\n";
}
$out .= "#endif //_INVINCIBILITYSTARSDATA_H\n";
open my $o, '>', 'src/Object/InvincibilityStarsData.h' or die $!;
print $o $out;
close $o;

system('cp', "$base/Data/Art/InvStars.nem", 'res/Art/Invincibility') == 0 or die;
system('perl', 'tools/asm_dc_mappings.pl', "$base/S2140992.asm", 'Invicibility_Stars_Mappings', 'res/Mappings/InvincibilityStars') == 0 or die "mappings\n";
print "invincibility stars imported\n";
