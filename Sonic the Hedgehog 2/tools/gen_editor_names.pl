#!/usr/bin/perl
# Writes src/Sonic2EditorNames.c: the names the built-in level editor lists for Sonic 2's object ids, taken from the handler each id has in src/Sonic2Objects.c ("Obj_SwingDispatch" is "Swing Dispatch"),
# and the folders its saved layouts go in. Ids that run nothing (Obj_Null) get no name. Run in the Sonic 2 folder: gen_editor_names.pl
use strict;
use warnings;

open my $in, '<', 'src/Sonic2Objects.c' or die "src/Sonic2Objects.c: $!\n";
my %name;
while (<$in>) {
    next unless m{^\s*/\*\s*([0-9A-Fa-f]{2})\s+\S+\s*\*/\s*(Obj_\w+)\s*,};
    my ($id, $fn) = (hex($1), $2);
    next if $fn eq 'Obj_Null';
    (my $n = $fn) =~ s/^Obj_//;
    $n =~ s/_/ /g;
    $n =~ s/([a-z0-9])([A-Z])/$1 $2/g;
    $n =~ s/([A-Z]+)([A-Z][a-z])/$1 $2/g;
    $name{$id} = $n;
}
close $in;

open my $out, '>', 'src/Sonic2EditorNames.c' or die "$!\n";
print $out <<'EOT';
// GENERATED by tools/gen_editor_names.pl from src/Sonic2Objects.c: what the built-in level editor calls Sonic 2's object ids (an id that runs nothing has no name), and where its saved layouts belong.
#include "DebugPeek.h"

static const char *const object_names[0x100] = {
EOT
for my $id (sort { $a <=> $b } keys %name) {
    printf $out "    [0x%02X] = \"%s\",\n", $id, $name{$id};
}
print $out <<'EOT';
};

const char *Peek_ObjectName(int id) {
    return id >= 0 && id < 0x100 ? object_names[id] : (const char *)0;
}

// The folders of res/ the layouts are kept in (a level's name in them comes with the level data: Peek_LevelName)
const char *Peek_LevelObjectsFolder(void) { return "S2Objects"; }
const char *Peek_LevelRingsFolder(void) { return "S2Rings"; }
EOT
close $out;
print scalar(keys %name), " object names\n";
